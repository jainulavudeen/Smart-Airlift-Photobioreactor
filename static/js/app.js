/* Shared client: socket connection, API helper, formatters, top bar, charts. */
const PBR = (() => {
  const socket = io();
  const handlers = { status: [], reading: [], alert: [], led_event: [], run_update: [], serial_log: [] };
  let status = null;

  Object.keys(handlers).forEach((ev) =>
    socket.on(ev, (data) => {
      if (ev === "status") status = data;
      handlers[ev].forEach((fn) => fn(data));
    })
  );
  const on = (ev, fn) => { handlers[ev].push(fn); if (ev === "status" && status) fn(status); };

  // ---------------------------------------------------------------- API
  async function api(method, url, body) {
    const res = await fetch(url, {
      method,
      headers: body ? { "Content-Type": "application/json" } : {},
      body: body ? JSON.stringify(body) : undefined,
    });
    const data = await res.json().catch(() => ({}));
    if (!res.ok || data.ok === false) throw new Error(data.error || `HTTP ${res.status}`);
    if (data.warning) toast(data.warning, "warning");
    return data;
  }

  // ---------------------------------------------------------------- formatters
  const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const fmtTemp = (t, d = 2) => (t === null || t === undefined ? "--" : Number(t).toFixed(d));
  const pad = (n) => String(n).padStart(2, "0");
  const fmtTime = (ts) => (ts ? new Date(ts * 1000).toLocaleTimeString([], { hour12: false }) : "--");
  const fmtDateTime = (ts) => {
    if (!ts) return "--";
    const d = new Date(ts * 1000);
    return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
  };
  function fmtDuration(sec, long = false) {
    if (sec == null || sec < 0) return "--";
    sec = Math.floor(sec);
    const d = Math.floor(sec / 86400), h = Math.floor((sec % 86400) / 3600), m = Math.floor((sec % 3600) / 60), s = sec % 60;
    if (long) return `${d > 0 ? d + "d " : ""}${pad(h)}:${pad(m)}:${pad(s)}`;
    if (d > 0) return `${d}d ${h}h ${m}m`;
    if (h > 0) return `${h}h ${m}m`;
    if (m > 0) return `${m}m ${s}s`;
    return `${s}s`;
  }
  const ago = (ts) => (ts ? fmtDuration(Date.now() / 1000 - ts) + " ago" : "never");

  const sourceBadge = (src) =>
    src === "hardware"
      ? '<span class="badge hw" title="Measured by the Arduino"><span class="dot"></span>HARDWARE</span>'
      : '<span class="badge sim" title="Generated by the built-in simulator"><span class="dot"></span>SIMULATED</span>';

  const TEMP_STATES = {
    normal: ["ok", "Within limits"],
    high: ["crit", "Above upper limit"],
    low: ["crit", "Below lower limit"],
    sensor_error: ["warn", "Sensor fault"],
    no_data: ["neutral", "No data"],
  };
  const tempStateBadge = (st) => {
    const [cls, label] = TEMP_STATES[st] || TEMP_STATES.no_data;
    const icon = cls === "ok" ? "✓" : cls === "neutral" ? "–" : "!";
    return `<span class="badge ${cls}">${icon} ${label}</span>`;
  };
  const alertClass = (lvl) => (lvl === "critical" ? "crit" : lvl === "warning" ? "warn" : "info");
  const alertIcon = (lvl) => (lvl === "critical" ? "⛔" : lvl === "warning" ? "⚠️" : "✅");

  // ---------------------------------------------------------------- toasts
  function toast(msg, type = "info", ms = 4000) {
    const box = document.getElementById("toasts");
    const el = document.createElement("div");
    el.className = `toast ${type}`;
    el.textContent = msg;
    box.appendChild(el);
    setTimeout(() => el.remove(), ms);
  }

  // ---------------------------------------------------------------- top bar
  function renderTopbar(s) {
    const src = s.source || (s.data_mode === "serial" ? "hardware" : "simulated");
    document.getElementById("sourceBadge").innerHTML =
      src === "hardware"
        ? '<span class="badge hw live"><span class="dot"></span>LIVE HARDWARE</span>'
        : '<span class="badge sim live"><span class="dot"></span>SIMULATED DATA</span>';
    document.getElementById("connBadge").innerHTML = s.connected
      ? `<span class="badge ok"><span class="dot"></span>${src === "hardware" ? "Arduino connected" : "Simulator running"}</span>`
      : `<span class="badge crit"><span class="dot"></span>${src === "hardware" ? "Arduino disconnected" : "Simulator stopped"}</span>`;
    const cnt = document.getElementById("alertCount");
    cnt.textContent = s.unacked_alerts > 99 ? "99+" : s.unacked_alerts;
    cnt.classList.toggle("hidden", !s.unacked_alerts);
    document.getElementById("simBanner").classList.toggle("hidden", src === "hardware");
    document.getElementById("footReactor").textContent = s.reactor_name;
    document.getElementById("footRun").textContent = s.active_run ? s.active_run.run_id : "Idle";
  }
  on("status", renderTopbar);
  on("alert", (a) => {
    if (a.level !== "info") toast(a.message, a.level, 6000);
    if (status) { status.unacked_alerts += 1; renderTopbar(status); }
  });
  socket.on("disconnect", () => toast("Lost connection to server - retrying…", "error"));

  setInterval(() => {
    const c = document.getElementById("clock");
    if (c) c.textContent = new Date().toLocaleString([], { hour12: false });
  }, 1000);

  // ---------------------------------------------------------------- mobile nav
  document.addEventListener("click", (e) => {
    if (e.target.closest("#menuBtn")) document.body.classList.toggle("nav-open");
    else if (e.target.closest(".overlay")) document.body.classList.remove("nav-open");
  });

  // ---------------------------------------------------------------- charts
  const css = (v) => getComputedStyle(document.documentElement).getPropertyValue(v).trim();

  // Draws the acceptable band (min..max) and dashed limit lines behind the data.
  const limitPlugin = {
    id: "limits",
    beforeDatasetsDraw(chart, _args, opts) {
      if (opts.min == null || opts.max == null) return;
      const { ctx, chartArea: a, scales: { y } } = chart;
      const yMax = y.getPixelForValue(opts.max), yMin = y.getPixelForValue(opts.min);
      ctx.save();
      ctx.fillStyle = "rgba(27,127,83,0.07)";
      const top = Math.max(a.top, yMax), bot = Math.min(a.bottom, yMin);
      if (bot > top) ctx.fillRect(a.left, top, a.right - a.left, bot - top);
      ctx.setLineDash([6, 4]);
      ctx.lineWidth = 1.5;
      ctx.strokeStyle = "rgba(192,57,43,0.8)";
      ctx.font = "600 11px system-ui, sans-serif";
      ctx.fillStyle = "rgba(192,57,43,0.95)";
      [[opts.max, "max"], [opts.min, "min"]].forEach(([v, l]) => {
        const py = y.getPixelForValue(v);
        if (py < a.top || py > a.bottom) return;
        ctx.beginPath(); ctx.moveTo(a.left, py); ctx.lineTo(a.right, py); ctx.stroke();
        ctx.fillText(`${l} ${v} °C`, a.right - 70, l === "max" ? py - 5 : py + 13);
      });
      ctx.restore();
    },
  };

  // Shaded vertical bands where the LED was ON (optional).
  const ledPlugin = {
    id: "ledBands",
    beforeDatasetsDraw(chart, _args, opts) {
      if (!opts.bands || !opts.bands.length) return;
      const { ctx, chartArea: a, scales: { x } } = chart;
      ctx.save();
      ctx.fillStyle = "rgba(245,183,0,0.10)";
      opts.bands.forEach(([s, e]) => {
        const x1 = Math.max(a.left, x.getPixelForValue(s)), x2 = Math.min(a.right, x.getPixelForValue(e));
        if (x2 > x1) ctx.fillRect(x1, a.top, x2 - x1, a.bottom - a.top);
      });
      ctx.restore();
    },
  };

  const SERIES = {
    hardware: { label: "Hardware", color: "#1b7f53" },
    simulated: { label: "Simulated", color: "#b26a00" },
  };

  function tempChart(canvas, { sources = ["simulated"], min, max, showLegend = false } = {}) {
    Chart.defaults.font.family = getComputedStyle(document.body).fontFamily;
    Chart.defaults.color = css("--muted");
    return new Chart(canvas, {
      type: "line",
      data: {
        datasets: sources.map((s) => ({
          label: SERIES[s].label + " temperature",
          source: s,
          data: [],
          borderColor: SERIES[s].color,
          backgroundColor: SERIES[s].color,
          borderWidth: 2,
          pointRadius: 0,
          pointHoverRadius: 5,
          pointHoverBorderWidth: 2,
          pointHoverBorderColor: "#fff",
          tension: 0.25,
          spanGaps: false,
        })),
      },
      options: {
        responsive: true,
        maintainAspectRatio: false,
        animation: false,
        parsing: false,
        normalized: true,
        interaction: { mode: "nearest", axis: "x", intersect: false },
        scales: {
          x: {
            type: "time",
            time: { tooltipFormat: "yyyy-MM-dd HH:mm:ss", displayFormats: { second: "HH:mm:ss", minute: "HH:mm", hour: "MMM d HH:mm", day: "MMM d" } },
            grid: { display: false },
            border: { color: css("--border") },
            ticks: { maxRotation: 0, autoSkipPadding: 18 },
          },
          y: {
            title: { display: true, text: "Temperature (°C)" },
            grid: { color: "rgba(17,39,29,0.06)" },
            border: { display: false },
            grace: "5%",
          },
        },
        plugins: {
          legend: { display: showLegend, position: "top", align: "end", labels: { boxWidth: 12, boxHeight: 12, usePointStyle: true } },
          tooltip: {
            backgroundColor: "#11271d",
            padding: 10,
            displayColors: true,
            callbacks: { label: (c) => ` ${c.parsed.y.toFixed(2)} °C  (${SERIES[c.dataset.source].label})` },
          },
          decimation: { enabled: true, algorithm: "lttb", samples: 1500 },
          limits: { min, max },
          ledBands: { bands: [] },
        },
      },
      plugins: [limitPlugin, ledPlugin],
    });
  }

  // Ensure the y-axis always shows the limit lines.
  function fitLimits(chart, min, max) {
    chart.options.plugins.limits = { min, max };
    chart.options.scales.y.suggestedMin = min - 1;
    chart.options.scales.y.suggestedMax = max + 1;
  }

  // Load DB readings into a chart, split into hardware / simulated series.
  function setReadings(chart, readings) {
    chart.data.datasets.forEach((ds) => {
      ds.data = readings.filter((r) => r.source === ds.source && r.temperature !== null)
        .map((r) => ({ x: r.ts * 1000, y: r.temperature }));
    });
    refreshLegend(chart);
  }
  function pushReading(chart, r, windowMs) {
    if (r.temperature === null) return;
    const ds = chart.data.datasets.find((d) => d.source === r.source);
    if (!ds) return;
    ds.data.push({ x: r.ts * 1000, y: r.temperature });
    if (windowMs) {
      const cutoff = Date.now() - windowMs;
      chart.data.datasets.forEach((d) => { while (d.data.length && d.data[0].x < cutoff) d.data.shift(); });
    }
    refreshLegend(chart);
  }
  function refreshLegend(chart) {
    const used = chart.data.datasets.filter((d) => d.data.length).length;
    chart.options.plugins.legend.display = used > 1;
  }
  const chartHasData = (chart) => chart.data.datasets.some((d) => d.data.length);

  return {
    setReadings, pushReading, chartHasData,
    socket, on, api, toast, esc, fmtTemp, fmtTime, fmtDateTime, fmtDuration, ago,
    sourceBadge, tempStateBadge, alertClass, alertIcon, tempChart, fitLimits, SERIES,
    get status() { return status; },
  };
})();
